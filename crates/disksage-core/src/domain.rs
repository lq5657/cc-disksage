use std::path::PathBuf;

use serde::{Deserialize, Serialize};

pub type Timestamp = i64;

/// A volume as reported by the operating system.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct VolumeInfo {
    pub letter: char,
    pub label: String,
    pub filesystem: String,
    pub total_bytes: u64,
    pub free_bytes: u64,
}

/// Result of a full-volume or quick scan, persisted for history and the treemap.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct ScanSnapshot {
    pub id: String,
    pub volume: char,
    pub started_at: Timestamp,
    pub duration_ms: u64,
    pub total_bytes: u64,
    pub allocated_bytes: u64,
    pub free_bytes: u64,
    pub file_count: u64,
    pub dir_count: u64,
    pub error_count: u64,
    pub node_limit_hit: bool,
    pub top_dirs: Vec<DirNode>,
    pub large_files: Vec<LargeFile>,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct DirNode {
    pub name: String,
    pub path: PathBuf,
    pub allocated_bytes: u64,
    pub logical_bytes: u64,
    pub file_count: u64,
    pub children: Vec<DirNode>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LargeFile {
    pub path: PathBuf,
    pub allocated_bytes: u64,
    pub logical_bytes: u64,
    pub modified_at: Option<Timestamp>,
    pub extension: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MatchedPath {
    /// The rule template, for evidence display.
    pub template: String,
    /// The resolved absolute path. Never accepted directly from the frontend.
    pub resolved: PathBuf,
    pub bytes: u64,
    pub file_count: u64,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SampleFile {
    pub name: String,
    pub bytes: u64,
    pub modified_at: Option<Timestamp>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RiskLevel {
    Safe,
    Caution,
    Danger,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Recoverability {
    /// The data is regenerated by the application or downloaded again.
    Regenerable,
    /// The item is moved to the Windows Recycle Bin.
    RecycleBin,
    /// The item is moved to the application quarantine for a limited time.
    Quarantine,
    /// The action cannot be undone.
    Irreversible,
    /// The item contains user data and must never be selected by a rule.
    UserData,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SizeProvenance {
    Scanner,
    Helper,
    Estimated,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EvidenceSource {
    Rule,
    Scanner,
    AppDetection,
    Llm,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EvidenceKind {
    RuleProvenance,
    Path,
    Size,
    Age,
    FileType,
    SafetyCheck,
    AppDetection,
    LlmInference,
}

/// One fact in the per-item evidence chain. Claims are generated locally,
/// never by the LLM.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Evidence {
    pub id: String,
    pub source: EvidenceSource,
    pub kind: EvidenceKind,
    pub claim: String,
    pub path: Option<PathBuf>,
    pub bytes: Option<u64>,
    pub timestamp: Option<Timestamp>,
    pub rule_id: Option<String>,
    pub confidence: f32,
}

/// A cleanup candidate produced by a rule.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Finding {
    pub id: String,
    pub rule_id: String,
    pub rule_version: u32,
    pub category: String,
    pub title_zh: String,
    pub title_en: String,
    pub risk: RiskLevel,
    pub recoverability: Recoverability,
    pub requires_admin: bool,
    pub default_selected: bool,
    /// Exact resolved paths stay on the Rust side. The frontend only receives
    /// finding IDs and aggregate evidence.
    #[serde(skip)]
    pub targets: Vec<MatchedPath>,
    pub allocated_bytes: u64,
    pub logical_bytes: u64,
    pub file_count: u64,
    pub size_provenance: SizeProvenance,
    pub oldest_mtime: Option<Timestamp>,
    pub newest_mtime: Option<Timestamp>,
    pub ext_histogram: Vec<(String, u64)>,
    pub sample_files: Vec<SampleFile>,
    pub evidence: Vec<Evidence>,
    pub consequence: String,
    pub action: ActionSpec,
    pub llm: Option<LlmAssessment>,
}

/// A fixed action type. Rules reference these variants; they can never carry
/// arbitrary executables or arguments.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ActionSpec {
    Trash,
    Delete,
    Quarantine,
    EmptyRecycleBin,
    ServiceCleanup {
        services: Vec<String>,
        paths: Vec<PathBuf>,
    },
    DismAnalyze,
    DismStartComponentCleanup,
    Guided(GuideId),
    HibernateOff,
    CreateRestorePoint,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum GuideId {
    WindowsStorageSettings,
    WindowsUpdateSettings,
    SystemProtection,
    PagefileSettings,
    CleanMgr,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Verdict {
    Cleanable,
    Review,
    DoNotClean,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Confidence {
    Low,
    Medium,
    High,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ReasoningStep {
    pub text: String,
    pub evidence_ids: Vec<String>,
}

/// LLM output. The schema intentionally has no size/count fields; all numbers
/// displayed to the user come from the scanner/helper.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct LlmAssessment {
    pub schema_version: u32,
    pub finding_id: String,
    pub verdict: Verdict,
    pub confidence: Confidence,
    pub summary: String,
    pub reasoning: Vec<ReasoningStep>,
    pub cited_evidence_ids: Vec<String>,
    pub consequence: String,
    pub caveats: Vec<String>,
    pub model: String,
    pub generated_at: Timestamp,
    pub payload_hash: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PlanStatus {
    Draft,
    Previewed,
    Running,
    Completed,
    PartiallyCompleted,
    Cancelled,
    Failed,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PlanWarning {
    pub code: String,
    pub message_zh: String,
    pub message_en: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlanItem {
    pub finding_id: String,
    pub rule_id: String,
    pub title_zh: String,
    pub risk: RiskLevel,
    pub action: ActionSpec,
    /// Exact files validated at plan time. Never accepted from the frontend.
    #[serde(skip)]
    pub targets: Vec<PathBuf>,
    /// Roots from the source finding, used to re-validate targets before deletion.
    #[serde(skip)]
    pub allowed_roots: Vec<PathBuf>,
    pub estimated_bytes: u64,
    pub file_count: u64,
    pub recoverability: Recoverability,
    pub requires_admin: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CleanupPlan {
    pub id: String,
    pub snapshot_id: String,
    pub created_at: Timestamp,
    pub items: Vec<PlanItem>,
    pub total_allocated_bytes: u64,
    pub requires_admin: bool,
    pub warnings: Vec<PlanWarning>,
    pub status: PlanStatus,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct CleanupResult {
    pub job_id: String,
    pub freed_bytes: u64,
    pub deleted: u64,
    pub skipped_locked: Vec<PathBuf>,
    pub failed: Vec<(PathBuf, String)>,
    pub cancelled: bool,
    #[serde(default)]
    pub notes: Vec<String>,
}
